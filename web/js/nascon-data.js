/* ── Shared helpers ──────────────────────────────────────────────────
   Loaded before app.js and mobile.js, so both the phone planner and the
   Free Rooms panels (desktop and phone) read the agenda the same way. */

// Split one agenda venue string into the separate rooms in it: "Rawal Lab
// 1,4" and "Karakorum 1, 2, 3" carry their prefix onto the bare numbers,
// "C-401 to C-405" expands to each room, a trailing "D Block" stays with the
// room before it, and commas inside brackets ("Cafe, inside") are not splits.
function nasconSplitVenues(venue){
  const parts=[];
  let depth=0, cur='';
  for(const ch of String(venue||'')){
    if(ch==='(') depth++;
    if(ch===')') depth=Math.max(0,depth-1);
    if(!depth&&(ch===','||ch===';')){ parts.push(cur); cur=''; continue; }
    cur+=ch;
  }
  parts.push(cur);
  const out=[];
  let prefix='';
  parts.map(p=>p.trim()).filter(Boolean).forEach(p=>{
    if(/^[A-Z] Block$/.test(p)&&out.length){ out[out.length-1]+=', '+p; return; }
    if(/^\d+$/.test(p)&&prefix){ out.push(prefix+p); return; }
    const range=p.match(/^([A-Z]+-)(\d+)\s+to\s+\1(\d+)$/);
    if(range&&+range[3]>+range[2]&&+range[3]-+range[2]<20){
      for(let n=+range[2];n<=+range[3];n++) out.push(range[1]+n);
      return;
    }
    const m=p.match(/^(.*?\s)\d+$/);
    prefix=m?m[1]:'';
    out.push(p);
  });
  return out;
}

/* ── Free Rooms during NASCON ────────────────────────────────────────
   Classes are off for the fest, so on the three NASCON dates a room is busy
   only if a NASCON event is held in it. nasconRoomStatus() is what the Free
   Rooms code asks first:
     undefined  -> not a NASCON date, use the class timetable as normal
     null       -> NASCON date and the room is free in that slot
     {course,…} -> NASCON date and an event is using the room
   Agenda venues are written the way the posters say them ("DIT 1",
   "Margalla 3", "Karakorum 2"), so they are translated to the inventory's
   names ("D-IT Lab 1", "C-Margala 3", "A-KK-II"). Venues that are not
   bookable rooms (lawns, lobbies, courts) simply match nothing. */
const NASCON_ROMAN=['','I','II','III','IV'];
function nasconRoomCandidates(place){
  const p=String(place||'').replace(/\s*\(.*?\)\s*/g,' ').replace(/\s+/g,' ').replace(/ ,/g,',').trim();
  let m;
  if((m=p.match(/^([A-D])-(\d{2,3})$/i))){
    const b=m[1].toUpperCase(), n=m[2];
    return [`${b}-${n}`, `${b}-${n.padStart(3,'0')}`];
  }
  if((m=p.match(/^DIT (\d)$/i))) return [`D-IT Lab ${m[1]}`];
  if((m=p.match(/^Margall?a (\d)$/i))) return [`C-Margala ${m[1]}`];
  if((m=p.match(/^Rawal Lab (\d)$/i))) return m[1]==='3'?['B-Rawal Lab 3']:[`C-Rawal ${m[1]}`];
  if(/^GPU Lab$/i.test(p)) return ['C-GPU Lab'];
  if((m=p.match(/^Khyber (\d)$/i))) return [`A-Khyber ${NASCON_ROMAN[+m[1]]||m[1]}`];
  if((m=p.match(/^Karakorum (\d)$/i))) return [`A-KK-${NASCON_ROMAN[+m[1]]||m[1]}`];
  if((m=p.match(/^Mehran (\d)$/i))) return [`A-Mehran ${m[1]}`];
  if((m=p.match(/^CAL (\d)$/i))) return [`A-CALL-${m[1]}`];
  if(/^Potohar \d$/i.test(p)) return ['B-Poth'];
  if(/^Kohsar Lab$/i.test(p)) return ['B-Koh'];
  if(/^Circuit Lab$/i.test(p)) return ['B-Ckt'];
  if(/^Electronics Lab$/i.test(p)) return ['B-Elect'];
  if(/^A Block Auditorium$/i.test(p)) return ['A-Audi'];
  if(/^D Block Auditorium$/i.test(p)) return ['D-Audi'];
  if(/^Cyber Lab$/i.test(p)) return ['@cyber'];
  // The EE digital lab is B-Digital; the CS one in D Block is not in the
  // room inventory, so it has no candidate.
  if(/^Digital Lab, B Block$/i.test(p)) return ['B-Digital'];
  if(/^All 3rd-floor classrooms, A Block$/i.test(p)) return ['@A3'];
  return [];
}
// room key (normalizeRoomName) -> [{date,start,end,name}], rebuilt when the
// room inventory object changes (BLOCK_FLOORS is replaced, never mutated).
let _nasconRoomIndex=null, _nasconIndexFloors=null;
function nasconRoomIndex(){
  const floors=(typeof BLOCK_FLOORS!=='undefined'&&BLOCK_FLOORS)||{};
  if(_nasconRoomIndex&&_nasconIndexFloors===floors) return _nasconRoomIndex;
  const norm=r=>(typeof normalizeRoomName==='function'?normalizeRoomName(r):String(r).toUpperCase());
  const all=[];
  Object.keys(floors).forEach(b=>Object.keys(floors[b]||{}).forEach(f=>(floors[b][f]||[]).forEach(r=>all.push({b,f,r}))));
  const byKey=new Map(all.map(x=>[norm(x.r),x.r]));
  const resolve=c=>{
    if(c==='@cyber') return all.filter(x=>/cyber/i.test(x.r)).map(x=>x.r);
    if(c==='@A3') return ((floors.A||{})[3]||[]).filter(r=>typeof isLabRoom!=='function'||!isLabRoom(r));
    const hit=byKey.get(norm(c));
    return hit?[hit]:[];
  };
  const toMin=t=>{ const [h,mm]=String(t).split(':').map(Number); return h*60+(mm||0); };
  const index=new Map();
  (window.NASCON_AGENDA||[]).forEach(d=>d.events.forEach(([start,end,name,cat,venue])=>{
    const allDay=start==='all';
    const s=allDay?toMin('09:00'):toMin(start);
    const e=allDay||!end?toMin('22:00'):toMin(end);
    const rooms=new Set();
    nasconSplitVenues(venue).forEach(place=>nasconRoomCandidates(place).forEach(c=>resolve(c).forEach(r=>rooms.add(r))));
    rooms.forEach(r=>{
      const key=norm(r);
      if(!index.has(key)) index.set(key,[]);
      index.get(key).push({date:d.date,start:s,end:e,name});
    });
  }));
  _nasconRoomIndex=index; _nasconIndexFloors=floors;
  return index;
}
function nasconDateOf(day){
  return (typeof roomDateForDay==='function')?roomDateForDay(day):'';
}
function isNasconDate(date){
  return (window.NASCON_AGENDA||[]).some(d=>d.date===date);
}
function nasconRoomStatus(room,day,slot){
  const date=nasconDateOf(day);
  if(!date||!isNasconDate(date)) return undefined;
  const range=(typeof slotRange==='function')?slotRange(slot):null;
  if(!range) return null;
  const norm=(typeof normalizeRoomName==='function')?normalizeRoomName(room):String(room).toUpperCase();
  const hits=(nasconRoomIndex().get(norm)||[]).filter(e=>e.date===date&&e.start<range[1]&&e.end>range[0]);
  if(!hits.length) return null;
  return {course:hits.map(e=>e.name).join(' / '),dept:'NASCON',batch:'',section:'NASCON'};
}
// Weekdays the Free Rooms day pickers should offer on top of Mon–Sat: the
// coming Sunday when it is a NASCON day (Day 3).
function nasconExtraRoomDays(){
  return isNasconDate(nasconDateOf('Sunday'))?['Sunday']:[];
}
